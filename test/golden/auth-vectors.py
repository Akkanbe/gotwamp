#!/usr/bin/env python3
# Generates test/golden/auth-vectors.txt: the cryptography of the
# authenticated and encrypted TWAMP modes, computed independently of gotwamp
# with Python's hashlib/hmac (PBKDF2-HMAC-SHA1, HMAC-SHA1) and the openssl
# command (AES-128 ECB/CBC).
#
#   python3 test/golden/auth-vectors.py > test/golden/auth-vectors.txt
import hashlib
import hmac
import subprocess


def aes(mode, key, data, iv=None):
    """Encrypts data with openssl, without padding."""
    args = ["openssl", "enc", "-" + mode, "-K", key.hex(), "-nopad"]
    if iv is not None:
        args += ["-iv", iv.hex()]
    return subprocess.run(args, input=data, capture_output=True, check=True).stdout


def mac(key, data):
    """HMAC-SHA1 truncated to 16 octets (RFC 4656 §3.2)."""
    return hmac.new(key, data, hashlib.sha1).digest()[:16]


def seq(start, n):
    return bytes(range(start, start + n))


zero_iv = bytes(16)
salt, challenge = seq(0x00, 16), seq(0x10, 16)
aes_key, hmac_key = seq(0x20, 16), seq(0x30, 32)
sid, client_iv, server_iv = seq(0x50, 16), seq(0x60, 16), seq(0x70, 16)

print("# Generated by auth-vectors.py (Python hashlib/hmac + openssl), independent of")
print("# gotwamp. Inputs: passphrase \"secretpass\", Salt 00..0f, Count 2048,")
print("# Challenge 10..1f, AES session key 20..2f, HMAC session key 30..4f,")
print("# SID 50..5f, Client-IV 60..6f, Server-IV 70..7f.")

# Key derivation and Token (RFC 4656 §3.1).
dk = hashlib.pbkdf2_hmac("sha1", b"secretpass", salt, 2048, 16)
print("dk", dk.hex())
print("token", aes("aes-128-cbc", dk, challenge + aes_key + hmac_key, zero_iv).hex())

# Test-session keys (RFC 5357 §4.2.1).
test_aes = aes("aes-128-ecb", sid, aes_key)
test_hmac = aes("aes-128-cbc", sid, hmac_key, zero_iv)
print("testaes", test_aes.hex())
print("testhmac", test_hmac.hex())


def seal(plain, covered, hmac_at):
    """HMAC over the covered octets, then ECB (one block) or CBC over them."""
    p = bytearray(plain)
    p[hmac_at:hmac_at + 16] = mac(test_hmac, bytes(p[:covered]))
    if covered == 16:
        p[:covered] = aes("aes-128-ecb", test_aes, bytes(p[:covered]))
    else:
        p[:covered] = aes("aes-128-cbc", test_aes, bytes(p[:covered]), zero_iv)
    return bytes(p)


# Session-Sender packet: Seq 7, Timestamp 0102..08 at 16, Error Estimate
# 8001 at 24, HMAC at 32, 4 octets of padding aa.
sender = bytearray(48)
sender[0:4] = (7).to_bytes(4, "big")
sender[16:24] = bytes.fromhex("0102030405060708")
sender[24:26] = bytes.fromhex("8001")
print("sender_auth", (seal(sender, 16, 32) + b"\xaa" * 4).hex())
print("sender_enc", (seal(sender, 32, 32) + b"\xaa" * 4).hex())

# Session-Reflector packet: Seq 3, Timestamp 1112..18, Error Estimate 8002,
# Receive Timestamp 2122..28, Sender Seq 7, Sender Timestamp 0102..08,
# Sender Error Estimate 8001, Sender TTL 64, HMAC at 96.
refl = bytearray(112)
refl[0:4] = (3).to_bytes(4, "big")
refl[16:24] = bytes.fromhex("1112131415161718")
refl[24:26] = bytes.fromhex("8002")
refl[32:40] = bytes.fromhex("2122232425262728")
refl[48:52] = (7).to_bytes(4, "big")
refl[64:72] = bytes.fromhex("0102030405060708")
refl[72:74] = bytes.fromhex("8001")
refl[80] = 64
print("reflector_auth", seal(refl, 16, 96).hex())
print("reflector_enc", seal(refl, 96, 96).hex())

# Control streams (RFC 4656 §3.2, §3.4). Client: Request-TW-Session
# (command 5, IPVN 4, zeros) whose HMAC covers octets 0-95 only.
req = bytearray(112)
req[0], req[1] = 5, 4
req[96:112] = mac(hmac_key, bytes(req[:96]))
print("request", aes("aes-128-cbc", aes_key, bytes(req), client_iv).hex())

# Server: the Start-Time block of Server-Start (Start-Time e0.., MBZ) opens
# the stream; the HMAC of the first Accept-Session (port 862, the SID)
# covers that block and Accept-Session 0-31.
start_block = bytes.fromhex("e000000000000000") + bytes(8)
acc = bytearray(48)
acc[2:4] = (862).to_bytes(2, "big")
acc[4:20] = sid
acc[32:48] = mac(hmac_key, start_block + bytes(acc[:32]))
stream = aes("aes-128-cbc", aes_key, start_block + bytes(acc), server_iv)
print("serverstart_block", stream[:16].hex())
print("accept", stream[16:].hex())
